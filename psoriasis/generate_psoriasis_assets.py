"""Generate current psoriasis manuscript tables and numerical macros from verified CSVs."""
from pathlib import Path
import argparse,json
import pandas as pd
import numpy as np
ROOT=Path(__file__).resolve().parent


def generate(out):
    source=out/'psoriasis' if (out/'psoriasis/psoriasis_summary.csv').exists() else ROOT/'psoriasis_results'
    out.mkdir(parents=True,exist_ok=True)
    summary=pd.read_csv(source/'psoriasis_summary.csv').set_index('model')
    def table(name,rows):
        (out/name).write_text('% Generated by generate_psoriasis_assets.py from verified CSVs.\n'+
                              '\n'.join(' & '.join(map(str,r))+r' \\' for r in rows)+'\n')
    rows=[]
    for title,key,denom in [('Nominal treatment pairs','total_targets',None),
                            ('Pairs with positive indirect mass','positive_indirect_targets',None),
                            ('Pairs with direct evidence only','direct_only_targets',None),
                            ('Unique study provenance, indirect targets','study_unique_positive',42),
                            ('Unique after treatment coarsening, indirect targets','treatment_unique_positive',42),
                            ('Unique study provenance, all targets','study_unique_all',45),
                            ('Unique after treatment coarsening, all targets','treatment_unique_all',45)]:
        rows.append([title]+[str(int(summary.loc[m,key]))+(f'/{denom}' if denom else '') for m in ['common','random']])
    for title,key in [('Largest study-labelled route width','study_max_width'),('Largest treatment-level route width','treatment_max_width')]:
        rows.append([title]+[f'{summary.loc[m,key]:.6f}' for m in ['common','random']])
    table('table_psoriasis_main_rows.tex',rows)
    c=pd.read_csv(source/'psoriasis_route_audit_common.csv').set_index('target')
    r=pd.read_csv(source/'psoriasis_route_audit_random.csv').set_index('target')
    assert c.index.equals(r.index) and (c.study_paths==r.study_paths).all()
    rows=[]
    for target,z in c.iterrows():
        if z.has_indirect:
            widths=[f'{df.loc[target,key]:.6f}' for df,key in [(c,'study_max_width'),(r,'study_max_width'),(c,'treatment_max_width'),(r,'treatment_max_width')]]
            label=target+(r'$^\ast$' if z.study_unique else '')
            rows.append([label,f'{z.indirect_weight:.6f}',int(z.study_paths),*widths])
        else:rows.append([target,'0','0','--','--','--','--'])
    table('table_psoriasis_full_rows.tex',rows)
    events=pd.read_csv(source/'psoriasis_DF_event_bounds.csv')
    labels={'visits_Study_7':'Visits study 7','visits_Study_10':'Visits study 10',
            'visits_both_Study_7_Study_10':'Visits both studies 7 and 10'}
    rows=[]
    for event,label in labels.items():
        rr=events[events.event==event].set_index('model')
        rows.append([label]+[f'$[{rr.loc[m,"lower"]:.6f},{rr.loc[m,"upper"]:.6f}]$' for m in ['common','random']])
    table('table_psoriasis_events_rows.tex',rows)
    verify=json.loads((source/'psoriasis_verification.json').read_text())
    numbers={'PsoTauSq':f'{summary.loc["random","tau2"]:.6f}',
             'PsoTau':f'{np.sqrt(summary.loc["random","tau2"]):.6f}',
             'PsoMaxCommon':f'{summary.loc["common","study_max_width"]:.6f}',
             'PsoMaxRandom':f'{summary.loc["random","study_max_width"]:.6f}',
             'PsoTreatMaxCommon':f'{summary.loc["common","treatment_max_width"]:.6f}',
             'PsoTreatMaxRandom':f'{summary.loc["random","treatment_max_width"]:.6f}',
             'PsoRouteChecks':str(verify['route_queries_checked']),
             'PsoSevenMass':f'{events.query("model==\"common\" and event==\"visits_Study_7\"").iloc[0].lower:.6f}',
             'PsoTenMass':f'{events.query("model==\"common\" and event==\"visits_Study_10\"").iloc[0].lower:.6f}',
             'PsoJointRandom':f'{events.query("model==\"random\" and event==\"visits_both_Study_7_Study_10\"").iloc[0].upper:.6f}'}
    (out/'psoriasis_numbers.tex').write_text('% Generated from psoriasis verified results.\n'+
          '\n'.join('\\newcommand{\\'+key+'}{'+value+'}' for key,value in numbers.items())+'\n')


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output-dir',type=Path,default=ROOT/'reproduced');generate(p.parse_args().output_dir)
